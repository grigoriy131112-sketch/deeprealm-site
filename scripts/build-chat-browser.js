// Bundles the chat modules into one classic script the page can load.
//
// app.js is a plain script and the tests run it that way, so the chat logic is
// flattened into a single IIFE instead of becoming an ES module. The output
// exposes window.DeeprealmChat and is written next to the other public files, so
// the browser can answer even when no server is reachable.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'chat-browser.js');

// Both modules share one scope, so their cross-references keep working. Only the
// module syntax is removed; no code is rewritten.
const strip = (code) => code
  .replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];\s*$/gm, '')
  .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
  .replace(/^export\s+(async\s+function|function|const|let|class)\s+/gm, '$1 ');

const parts = ['chat-core.js', 'ai-engine.js', 'ai-maker.js', 'telegram.js', 'chat-answers.js'].map((name) => {
  const file = path.join(root, name);
  if (!fs.existsSync(file)) throw new Error(`missing source: ${name}`);
  return `// ---- ${name} ----\n${strip(fs.readFileSync(file, 'utf8'))}`;
});

const bundle = `// Generated by scripts/build-chat-browser.js - do not edit by hand.
//
// The chat rules and the built-in AI (chat-core.js, ai-engine.js, ai-maker.js,
// telegram.js, chat-answers.js) flattened so the page can use them with no server.
// The built-in engine is what keeps the chats answering when the hosting sandbox is
// asleep, and the notifier is what lets the static site still message the owner.
(function () {
${parts.join('\n\n')}

  // A keyless public endpoint, used only as an optional wording upgrade. Nothing
  // secret is embedded here: the owner's private key never reaches the browser.
  // When it is down - which it often is - the built-in engine above answers.
  //
  // The endpoint rejects a "system" role, so the rules are folded into the first
  // user turn, which it accepts. One function serves the model slot for all three
  // chats, so static hosting gets the upgrade too.
  function flattenSystem(messages) {
    var rules = [];
    var rest = [];
    (messages || []).forEach(function (m) {
      if (m && m.role === 'system') rules.push(String(m.content || ''));
      else rest.push({ role: m && m.role === 'assistant' ? 'assistant' : 'user', content: String((m && m.content) || '') });
    });
    if (!rules.length) return rest;
    var head = { role: 'user', content: rules.join('\\n\\n') };
    if (!rest.length) return [head];
    return [head].concat(rest);
  }

  // A dead endpoint must not delay the built-in answer waiting behind it, so the
  // call is aborted after a few seconds and a failure pauses tries for a while.
  var modelDownUntil = 0;

  function callModel(messages, options) {
    options = options || {};
    if (Date.now() < modelDownUntil) return Promise.reject(new Error('model is resting'));
    var controller = typeof AbortController === 'function' ? new AbortController() : null;
    var timer = controller ? setTimeout(function () { controller.abort(); }, 8000) : null;
    return fetch('https://text.pollinations.ai/openai', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: 'openai-fast',
        messages: flattenSystem(messages),
        temperature: options.temperature == null ? 0.6 : options.temperature
      }),
      signal: controller ? controller.signal : undefined
    }).then(function (res) {
      if (!res.ok) throw new Error('model error ' + res.status);
      return res.json();
    }).then(function (data) {
      var reply = (data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content) || '';
      if (!String(reply).trim()) throw new Error('empty model reply');
      return reply;
    }).catch(function (err) {
      modelDownUntil = Date.now() + 10 * 60 * 1000;
      throw err;
    }).finally(function () {
      if (timer) clearTimeout(timer);
    });
  }

  setModelCaller(callModel);

  // Without a server there is no article builder, so a sheet is recognised by its
  // own markers. That is enough to approve and hand off; the owner gets the sheet
  // itself, and publishing an article stays with them.
  function sheetKind(messages, application) {
    var text = (Array.isArray(messages) ? messages.map(function (m) { return String(m && m.content || ''); }).join('\\n') : '') + '\\n' + JSON.stringify(application || {});
    var race = [/самоназвание/i, /особые приметы/i, /уязвимост/i, /форма правления/i, /социальная структура/i];
    var klass = [/роль\\s*:/i, /ресурс\\s*:/i, /\\bHP\\s*:/i, /\\bХП\\s*:/i, /базов\\s*урон/i];
    var count = function (list) { return list.filter(function (re) { return re.test(text); }).length; };
    if (count(klass) >= 3) return 'class';
    if (count(race) >= 3) return 'race';
    return 'character';
  }
  setSheetDetector(sheetKind);

  // The live-speech layer, so the engine's answer is rewritten in a natural voice.
  // It uses the same free endpoint; when that is down the engine's own wording
  // stands, and the cooldown stops later messages from waiting on it.
  var speaker = createLiveSpeaker({
    timeoutMs: 9000,
    cooldownMs: 10 * 60 * 1000
  });
  if (speaker) setLiveCaller(function (messages, options) { return speaker(messages, options); });

  // The owner notifier. On static hosting there is no server to relay through, so
  // the page sends to Telegram directly; the token lives in data/telegram.json,
  // which ships empty. Until the owner fills it in every call is a no-op.
  var notifier = createNotifier({});
  var notifyReady = false;

  function loadTelegram() {
    if (notifyReady) return Promise.resolve(notifier);
    notifyReady = true;
    return fetch('data/telegram.json')
      .then(function (res) { return res.ok ? res.json() : null; })
      .catch(function () { return null; })
      .then(function (file) {
        if (file) notifier = createNotifier({ config: telegramConfig({}, file) });
        setNotifier(function (info) {
          return notifier.sheet(info);
        });
        return notifier;
      });
  }

  // One ping per browser session, so an open tab reloading does not spam the owner.
  function notifyVisit(info) {
    return loadTelegram().then(function (n) {
      return n.visit(info || {});
    });
  }

  window.DeeprealmChat = {
    setKnowledge: setKnowledge,
    setSheetDetector: setSheetDetector,
    setEngineArticles: setEngineArticles,
    setNotifier: setNotifier,
    setLiveCaller: setLiveCaller,
    loadTelegram: loadTelegram,
    notifyVisit: notifyVisit,
    answerGuide: answerGuide,
    answerInterview: answerInterview,
    answerStaff: answerStaff,
    needsModel: needsModel,
    withEnd: withEnd
  };
})();
`;

fs.writeFileSync(out, bundle);
console.log(`chat-browser.js ready: ${bundle.split('\n').length} lines`);
