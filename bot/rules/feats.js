// A rating of 8 opens the feat; 10 upgrades it; 9 is still the base.
export function featFor(statKey, value) {
  const feat = FEATS[statKey];
  if (!feat) return null;
  const n = Number(value);
  if (!Number.isFinite(n) || n < 8) return null;
  return n >= 10 ? { ...feat, tier: 10 } : { ...feat, tier: 8 };
}
