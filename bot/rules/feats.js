// A feat opens only at a rating of 10; 8 and 9 unlock nothing.
export function featFor(statKey, value) {
  const feat = FEATS[statKey];
  if (!feat) return null;
  const n = Number(value);
  if (!Number.isFinite(n) || n < 10) return null;
  return { ...feat, tier: 10 };
}
