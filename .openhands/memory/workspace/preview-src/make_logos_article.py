def post(method, **params):
    data = urllib.parse.urlencode(params).encode()
    with urllib.request.urlopen(urllib.request.Request(API + method, data=data), timeout=90) as r:
        return json.loads(r.read().decode())


def upload(path):
    """Загружает картинку в Telegraph и возвращает её адрес."""
    boundary = uuid.uuid4().hex
    with open(path, "rb") as f:
        blob = f.read()
    ctype = mimetypes.guess_type(path)[0] or "image/png"
    body = (
        f"--{boundary}\r\n"
        f'Content-Disposition: form-data; name="file"; filename="{path.split("/")[-1]}"\r\n'
        f"Content-Type: {ctype}\r\n\r\n"
    ).encode() + blob + f"\r\n--{boundary}--\r\n".encode()
    req = urllib.request.Request(
        "https://telegra.ph/upload", data=body,
        headers={"Content-Type": f"multipart/form-data; boundary={boundary}"})
    with urllib.request.urlopen(req, timeout=120) as r:
        res = json.loads(r.read().decode())
    if isinstance(res, list) and res and "src" in res[0]:
        return "https://telegra.ph" + res[0]["src"]
    raise RuntimeError(f"загрузка не удалась: {res}")


def p(t):  return {"tag": "p", "children": t if isinstance(t, list) else [t]}
def b(t):  return {"tag": "b", "children": [t]}
def h3(t): return {"tag": "h3", "children": [t]}
def h4(t): return {"tag": "h4", "children": [t]}
def li(t): return {"tag": "li", "children": t if isinstance(t, list) else [t]}
def ul(i): return {"tag": "ul", "children": [li(x) for x in i]}


def a(text, href):
    return {"tag": "a", "attrs": {"href": href}, "children": [text]}


def img(src, cap=None):
    d = {"tag": "figure", "children": [{"tag": "img", "attrs": {"src": src}}]}
    if cap:
        d["children"].append({"tag": "figcaption", "children": [cap]})
    return d


def code(t):
    return {"tag": "code", "children": [t]}


